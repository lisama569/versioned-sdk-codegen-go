package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"unicode"

	"github.com/lisama569/versioned-sdk-codegen-go/internal/model"
)

// renderEnum 渲染一个枚举：枚举类型 + 全部取值常量。
// 取值按模型中已排序的顺序输出，保证产物稳定。
func renderEnum(e *model.Enum, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by sdkgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// %s 是由 schema 生成的字符串枚举。\n", e.Name)
	fmt.Fprintf(&b, "type %s string\n\n", e.Name)
	fmt.Fprintf(&b, "const (\n")
	for _, v := range e.Values {
		fmt.Fprintf(&b, "\t%s%s %s = %q\n", e.Name, enumValueIdent(v), e.Name, v)
	}
	fmt.Fprintf(&b, ")\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("渲染枚举 %s 失败: %w", e.Name, err)
	}
	return src, nil
}

// renderEntity 渲染一个实体结构体。
// 字段按模型中已排序的顺序输出；JSON tag 携带 omitempty 以表达可选语义。
func renderEntity(e *model.Entity, sc *model.Schema, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by sdkgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// %s 是由 schema 生成的实体模型。\n", e.Name)
	fmt.Fprintf(&b, "type %s struct {\n", e.Name)
	for _, f := range e.Fields {
		goType := goType(f, sc)
		tag := f.Name
		if f.Optional {
			tag += ",omitempty"
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.Name, goType, tag)
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("渲染实体 %s 失败: %w", e.Name, err)
	}
	return src, nil
}

func goType(f model.Field, sc *model.Schema) string {
	// 枚举与实体渲染到同一个 Go 包，因此枚举字段直接引用枚举类型名。
	_ = sc
	if f.EnumRef != "" {
		return f.EnumRef
	}
	switch f.Type {
	case model.TypeInteger:
		return "int64"
	case model.TypeNumber:
		return "float64"
	case model.TypeBoolean:
		return "bool"
	default:
		return "string"
	}
}

// enumValueIdent 把枚举取值转成可作为 Go 标识符后缀的形式。
func enumValueIdent(v string) string {
	var b strings.Builder
	upper := true
	for _, r := range v {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			if upper {
				b.WriteRune(unicode.ToUpper(r))
			} else {
				b.WriteRune(r)
			}
			upper = false
		default:
			upper = true
		}
	}
	id := b.String()
	if id == "" || unicode.IsDigit(rune(id[0])) {
		id = "V" + id
	}
	return id
}

// snakeCase 把 CamelCase 名称转成 snake_case 文件名。
func snakeCase(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}
