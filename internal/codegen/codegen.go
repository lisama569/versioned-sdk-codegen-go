// Package codegen 依据内部模型生成版本化客户端代码。
//
// 可复现性保证：
//
//   - 渲染输入（internal/model.Schema）在归一化阶段已排序，
//     渲染过程不读取环境变量、当前时间或 map 的随机遍历顺序；
//   - 全部文件先渲染到内存并通过 go/format 格式化，
//     任何一处渲染/格式化失败都会在触碰输出目录前返回错误；
//   - 文件先写入同级暂存目录，再整体重命名替换目标目录，
//     生成失败时清理暂存目录，输出目录保持生成前状态，不留半截产物；
//   - 同一输出目录上的并发生成由互斥锁串行化，
//     因此"同一份 schema 并发触发 N 次"的结果与串行执行完全一致。
package codegen

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"

	"github.com/lisama569/versioned-sdk-codegen-go/internal/model"
)

// Options 控制一次代码生成的行为。
type Options struct {
	// PackageName 是生成代码的 Go 包名；为空时使用默认值 "sdk"。
	PackageName string
}

// Result 是一次成功生成的产物描述。
type Result struct {
	// Files 是生成文件相对 outDir 的路径，按字典序排列。
	Files []string
}

// Generator 负责把 schema 生成到文件系统。
type Generator struct {
	muMapLock sync.Mutex
	locks     map[string]*sync.Mutex
}

// New 创建一个生成器。
func New() *Generator {
	return &Generator{locks: map[string]*sync.Mutex{}}
}

func (g *Generator) lockFor(dir string) *sync.Mutex {
	g.muMapLock.Lock()
	defer g.muMapLock.Unlock()
	if m, ok := g.locks[dir]; ok {
		return m
	}
	m := &sync.Mutex{}
	g.locks[dir] = m
	return m
}

// Generate 把 schema 生成到 outDir。
// 同一 schema 并发生成的结果必须与串行一致且可复现；
// 失败时不得留下半截产物（回滚到生成前状态）。
func (g *Generator) Generate(ctx context.Context, sc *model.Schema, outDir string, opts Options) (result *Result, err error) {
	if sc == nil {
		return nil, errors.New("schema 为空，无法生成")
	}
	if opts.PackageName == "" {
		opts.PackageName = "sdk"
	}

	g.lockFor(outDir).Lock()
	defer g.lockFor(outDir).Unlock()

	// 先在内存中完成全部渲染与格式化，失败时输出目录完全不受影响。
	files, err := render(sc, opts.PackageName)
	if err != nil {
		return nil, err
	}

	// 检查取消状态：已渲染但尚未写盘时直接放弃。
	if err := ctx.Err(); err != nil {
		return nil, err
	}

	parent := filepath.Dir(strings.TrimRight(outDir, string(os.PathSeparator)))
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return nil, fmt.Errorf("创建输出父目录失败: %w", err)
	}

	// 暂存目录与目标目录同级，保证 rename 是同文件系统操作。
	staging, err := os.MkdirTemp(parent, ".sdkgen-staging-*")
	if err != nil {
		return nil, fmt.Errorf("创建暂存目录失败: %w", err)
	}
	commit := false
	defer func() {
		if !commit {
			_ = os.RemoveAll(staging)
		}
	}()

	for name, content := range files {
		full := filepath.Join(staging, name)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return nil, fmt.Errorf("创建暂存子目录失败: %w", err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			return nil, fmt.Errorf("写入暂存文件 %s 失败: %w", name, err)
		}
	}

	if err := replaceDir(staging, outDir); err != nil {
		return nil, err
	}
	commit = true

	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	return &Result{Files: names}, nil
}

// replaceDir 用 staging 整体替换 target：target 被移出文件系统后，
// staging 重命名为 target；替换失败时尝试恢复 target，保证不出现
// "旧版本已删、新版本未就位"的半截状态。
func replaceDir(staging, target string) error {
	absTarget, err := filepath.Abs(target)
	if err != nil {
		return fmt.Errorf("解析输出目录失败: %w", err)
	}
	backup := absTarget + ".sdkgen-backup"
	_ = os.RemoveAll(backup)

	targetExisted := false
	if _, err := os.Lstat(absTarget); err == nil {
		targetExisted = true
		if err := os.Rename(absTarget, backup); err != nil {
			return fmt.Errorf("备份旧输出目录失败: %w", err)
		}
	}
	if err := os.Rename(staging, absTarget); err != nil {
		// 尝试回滚旧目录。
		if targetExisted {
			if rbErr := os.Rename(backup, absTarget); rbErr != nil {
				return fmt.Errorf("就位新产物失败 (%v)，且回滚旧目录也失败: %w", err, rbErr)
			}
		}
		return fmt.Errorf("就位新产物失败，已回滚: %w", err)
	}
	if targetExisted {
		_ = os.RemoveAll(backup)
	}
	return nil
}

// render 把 schema 渲染为 "相对路径 -> Go 源码" 的映射，
// 全部源码都会经过 gofmt。任何一个文件渲染失败都整体失败。
func render(sc *model.Schema, pkg string) (map[string]string, error) {
	files := map[string][]byte{}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by sdkgen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// SchemaVersion: %s\n\n", sc.Version)
	fmt.Fprintf(&b, "package %s\n", pkg)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("渲染 doc.go 失败: %w", err)
	}
	files["doc.go"] = src

	for i := range sc.Enums {
		e := &sc.Enums[i]
		src, err := renderEnum(e, pkg)
		if err != nil {
			return nil, err
		}
		filename := "enum_" + snakeCase(e.Name) + ".go"
		files[filename] = src
	}
	for i := range sc.Entities {
		e := &sc.Entities[i]
		src, err := renderEntity(e, sc, pkg)
		if err != nil {
			return nil, err
		}
		files["model_"+snakeCase(e.Name)+".go"] = src
	}

	out := make(map[string]string, len(files))
	for k, v := range files {
		out[k] = string(v)
	}
	return out, nil
}
