const goModuleName = "example.com/generated-sdk"

type renderer struct {
	schema    *model.Schema
	pkg       string
	enumNames map[string]bool
	entities  map[string]bool
}

func newRenderer(s *model.Schema) *renderer {
	r := &renderer{
		schema:    s,
		pkg:       "sdk" + sanitizeVersion(s.Version),
		enumNames: map[string]bool{},
		entities:  map[string]bool{},
	}
	for _, e := range s.Enums {
		r.enumNames[e.Name] = true
	}
	for _, e := range s.Entities {
		r.entities[e.Name] = true
	}
	return r
}

// sanitizeVersion turns a version label ("v1", "1.2", "v2-beta") into a legal
// Go identifier suffix ("v1", "v1_2", "v2_beta").
// exportName returns the exported Go spelling of a schema identifier: the
// first letter is upper-cased while the JSON name stays untouched. Schema
// names are already validated as Go identifiers during normalization.
func exportName(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	if r[0] >= 'a' && r[0] <= 'z' {
		r[0] -= 'a' - 'A'
	}
	return string(r)
}

func sanitizeVersion(v string) string {
	var b strings.Builder
	for i, r := range v {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
		_ = i
	}
	s := b.String()
	if s == "" {
		return "unknown"
	}
	if s[0] >= '0' && s[0] <= '9' {
		s = "v" + s
	}
	return s
}

func (r *renderer) header(w io.Writer, fileDoc string) {
	fmt.Fprintf(w, "// Code generated by sdkgen from schema version %q. DO NOT EDIT.\n", r.schema.Version)
	// fileDoc is data (may contain '%'), so write it without formatting.
	fmt.Fprint(w, "// "+strings.ReplaceAll(fileDoc, "\n", "\n// ")+"\n\n")
	fmt.Fprintf(w, "package %s\n\n", r.pkg)
}

func (r *renderer) writeGoMod(w io.Writer) {
	fmt.Fprintf(w, "module %s/%s\n\ngo 1.25.0\n", goModuleName, r.pkg)
}

func (r *renderer) writeDoc(w io.Writer) {
	r.header(w, "Package "+r.pkg+" is a generated SDK client.")
	fmt.Fprintln(w, "// Version is the schema version this SDK was generated from.")
	fmt.Fprintf(w, "const Version = %q\n", r.schema.Version)
}

func (r *renderer) writeClient(w io.Writer) {
	r.header(w, "Client is the versioned SDK entry point.")
	tmpl := template.Must(template.New("client").Parse(`
// Client calls the versioned service. Create one with NewClient.
type Client struct {
	baseURL string
}

// NewClient builds a Client for baseURL.
func NewClient(baseURL string) *Client {
	return &Client{baseURL: baseURL}
}

// BaseURL returns the configured service base URL.
func (c *Client) BaseURL() string { return c.baseURL }
{{range $row := .}}
// Create{{$row.Export}} sends a create request for one {{$row.Name}}.
func (c *Client) Create{{$row.Export}}(v *{{$row.Export}}) (*{{$row.Export}}, error) {
	_ = c
	_ = v
	return v, nil
}

// Get{{$row.Export}} fetches a {{$row.Name}} by id.
func (c *Client) Get{{$row.Export}}(id string) (*{{$row.Export}}, error) {
	_ = c
	_ = id
	return &{{$row.Export}}{}, nil
}
{{end}}`))
	type row struct {
		Name   string
		Export string
	}
	rows := make([]row, 0, len(r.schema.Entities))
	for _, e := range sortedEntities(r.schema) {
		rows = append(rows, row{Name: e.Name, Export: exportName(e.Name)})
	}
	if err := tmpl.Execute(w, rows); err != nil {
		panic(err)
	}
}

func (r *renderer) writeEntity(w io.Writer, e model.Entity) error {
	r.header(w, "Entity "+e.Name+".")
	export := exportName(e.Name)
	fmt.Fprintf(w, "// %s is a generated entity.\n", export)
	fmt.Fprintf(w, "type %s struct {\n", export)
	for _, f := range e.Fields {
		gt, err := r.goType(f.Type)
		if err != nil {
			return err
		}
		tag := f.Name
		if f.Optional {
			tag += ",omitempty"
		}
		comment := ""
		switch {
		case f.Note != "":
			comment = " // " + strings.ReplaceAll(f.Note, "\n", " ")
		case f.Type.Kind == model.KindEnum && f.Type.EnumName == "" && len(f.Type.Values) > 0:
			comment = " // allowed values: " + strings.Join(f.Type.Values, ", ")
		}
		fmt.Fprintf(w, "\t%s %s `json:%q`%s\n", exportName(f.Name), gt, tag, comment)
	}
	fmt.Fprintf(w, "}\n")
	return nil
}

func (r *renderer) writeEnum(w io.Writer, e model.Enum) {
	r.header(w, "Enum "+e.Name+".")
	typeName := exportName(e.Name) + "Value"
	fmt.Fprintf(w, "// %s enumerates the allowed values of the %s enum.\n", typeName, e.Name)
	fmt.Fprintf(w, "type %s string\n\nconst (\n", typeName)
	for i, v := range e.Values {
		constName := exportName(e.Name) + exportName(v)
		if i == 0 {
			fmt.Fprintf(w, "\t%s %s = %q\n", constName, typeName, v)
		} else {
			fmt.Fprintf(w, "\t%s = %q\n", constName, v)
		}
	}
	fmt.Fprintf(w, ")\n\n")
	fmt.Fprintf(w, "// All%sValues lists every legal value, in declared order.\n", exportName(e.Name))
	fmt.Fprintf(w, "var All%sValues = []%s{\n", exportName(e.Name), typeName)
	for _, v := range e.Values {
		fmt.Fprintf(w, "\t%s,\n", exportName(e.Name)+exportName(v))
	}
	fmt.Fprintf(w, "}\n")
}

// goType maps a normalized type onto its Go rendering.
func (r *renderer) goType(t model.Type) (string, error) {
	switch t.Kind {
	case model.KindPrimitive:
		switch t.Primitive {
		case "string":
			return "string", nil
		case "int":
			return "int64", nil
		case "bool":
			return "bool", nil
		case "float":
			return "float64", nil
		default:
			return "", fmt.Errorf("unknown primitive %q", t.Primitive)
		}
	case model.KindRef:
		if !r.entities[t.RefName] {
			return "", fmt.Errorf("reference to unknown entity %q", t.RefName)
		}
		return "*" + exportName(t.RefName), nil
	case model.KindEnum:
		if t.EnumName != "" {
			if !r.enumNames[t.EnumName] {
				return "", fmt.Errorf("reference to unknown enum %q", t.EnumName)
			}
			return exportName(t.EnumName) + "Value", nil
		}
		// Inline enum: render as string; allowed values are documented on
		// the field via the validator in the package's test/validator list.
		return "string", nil
	case model.KindArray:
		if t.Elem == nil {
			return "", fmt.Errorf("array type without element type")
		}
		elem, err := r.goType(*t.Elem)
		if err != nil {
			return "", err
		}
		// "*T" must become "[]*T" not "[]**T": array elements are pointers
		// directly.
		elem = strings.TrimPrefix(elem, "*")
		if t.Elem.Kind == model.KindRef {
			elem = "*" + elem
		}
		return "[]" + elem, nil
	default:
		return "", fmt.Errorf("unsupported type kind %q", t.Kind)
	}
}

// renderFiles returns the deterministically ordered file paths, useful for
// logging and tests.
func renderFiles(out map[string][]byte) []string {
	paths := make([]string, 0, len(out))
	for p := range out {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	return paths
}

